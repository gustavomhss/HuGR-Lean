async function executable(name, searchPath) {
  for (const directory of searchPath.split(path.delimiter)) {
    if (!path.isAbsolute(directory)) continue;
    const candidate = path.join(directory, name);
    try { await access(candidate, constants.X_OK); return { selected: candidate, resolved: await realpath(candidate) }; }
    catch (error) { if (!["ENOENT", "EACCES", "ENOTDIR"].includes(error.code)) throw error; }
  }
  throw new Error(`NATIVE_EXECUTABLE_DISCOVERY_FAILED: ${name}`);
}

async function collect() {
  assert.equal(process.argv.length, 2, "Usage: node scripts/utility-native-go.mjs");
  const privateParent = path.join(workspace, ".native-captures");
  await mkdir(privateParent, { recursive: true, mode: 0o700 });
  const root = await mkdtemp(path.join(privateParent, "go-"));
  const index = { schema: "hugr-lean/utility-native-prep/1", family: "go", baseline, root,
    createdAt: new Date().toISOString(), producer: {}, tools: [], sources: [], receipts: [], cases: [], failedCaptures: [],
    limits: ["Original local fixtures only; no historical corpus reruns or historical performance claims.",
      "Native duration is capture provenance, not filtering latency or representative build performance.",
      "No expected outputs, grammar freeze, parser acceptance or material savings measured.",
      "Arrival-order capture is pipe-chunk order, not a reconstructed total order of individual writes."] };
  const local = (file) => path.join(root, file);
  const artifact = async (file, bytes) => {
    await mkdir(path.dirname(local(file)), { recursive: true });
    await writeFile(local(file), bytes);
    const actual = await readFile(local(file));
    assert.deepEqual(actual, Buffer.from(bytes), `ARTIFACT_BYTES_CHANGED: ${file}`);
    return { file, bytes: actual.length, sha256: sha256(actual) };
  };
  const json = (file, value) => artifact(file, `${JSON.stringify(value, null, 2)}\n`);
  let env, active, blocker;
  const capture = async (id, cwd, literalCommand, fixtureSources = []) => {
    active = { id, command: literalCommand, cwd, timeout: 300000, fixtureSources };
    const prefix = `captures/${id}`;
    await json(`${prefix}/intent.json`, { ...active, baseline, environmentPolicy: index.environmentPolicy });
    let result;
    try { result = await captureCommand({ command: literalCommand, cwd }, env, { timeout: 300000, logDir: local(`${prefix}/live`) }); }
    catch (error) {
      const retained = {};
      for (const stream of ["original", "stdout", "stderr"]) {
        try { retained[stream] = await artifact(`${prefix}/${stream}.log`, await readFile(local(`${prefix}/live/${stream}.live`))); }
        catch (readError) { retained[`${stream}RecoveryError`] = readError.message; }
      }
      const failure = { ...active, phase: "capture", error: error.stack, retained, factsUnavailable: true };
      const receipt = await json(`${prefix}/failed-receipt.json`, failure);
      index.failedCaptures.push({ ...failure, receipt });
      active = undefined;
      throw error;
    }
    const original = await artifact(`${prefix}/original.log`, result.raw);
    const stdout = await artifact(`${prefix}/stdout.log`, result.stdout);
    const stderr = await artifact(`${prefix}/stderr.log`, result.stderr);
    const { raw, stdout: _stdout, stderr: _stderr, output, ...facts } = result;
    const receipt = await json(`${prefix}/receipt.json`, { ...facts, baseline, fixtureSources,
      environmentPolicy: index.environmentPolicy, tools: index.tools, producer: index.producer,
      original, stdout, stderr, errors: { launch: result.launchError ?? null, encoding: result.encodingError ?? null,
        cleanup: result.killErrors ?? [], preparation: null }, timeout: 300000 });
    const record = { id, ...facts, original, stdout, stderr, receipt, fixtureSources };
    index.receipts.push(record);
    active = undefined;
    if (!result.complete || !result.nativeSpawned || !result.nativeExitObserved || result.encodingError) {
      index.failedCaptures.push(record);
      throw new Error(`NATIVE_CAPTURE_INCOMPLETE: ${id}`);
    }
    return { record, output };
  };
  try {
    index.head = execFileSync("git", ["rev-parse", "HEAD"], { cwd: workspace, encoding: "utf8" }).trim();
    assert.equal(execFileSync("git", ["merge-base", "HEAD", baseline], { cwd: workspace, encoding: "utf8" }).trim(), baseline);
    index.producer = { script: "scripts/utility-native-go.mjs", sourceSHA256: sha256(await readFile(script)),
      dependencies: await Promise.all(["scripts/opencode-boundary.mjs", "scripts/real-world/capture.mjs",
        "scripts/real-world/owned-process.mjs", "scripts/real-world/process-guardian.mjs"].map(async (file) =>
        ({ file, sha256: sha256(await readFile(path.join(workspace, file))) }))) };
    index.producer.snapshot = await artifact("producer-source.mjs", await readFile(script));
    env = isolatedEnvironment(root, { GOENV: "off", GOWORK: "off", GOTOOLCHAIN: "local", GOPROXY: "off", GOSUMDB: "off",
      GOCACHE: local("go-cache"), GOMODCACHE: local("go-mod-cache"), GOPATH: local("go-path"), GOTMPDIR: local("go-tmp") });
    index.environmentPolicy = { helper: "isolatedEnvironment(privateRoot)", inherited: ["PATH only for executable discovery"],
      variables: Object.fromEntries(["HOME", "XDG_CONFIG_HOME", "XDG_DATA_HOME", "XDG_CACHE_HOME", "XDG_STATE_HOME", "TMPDIR",
        "GOENV", "GOWORK", "GOTOOLCHAIN", "GOPROXY", "GOSUMDB", "GOCACHE", "GOMODCACHE", "GOPATH", "GOTMPDIR"]
        .map((key) => [key, env[key]])), goFlags: "unset", network: "no dependency fetch; proxy/sumdb off; local toolchain",
      configuration: "No caller Go settings, Git writes, credential files or global installs; no cleanup deletes." };
    for (const directory of Object.values(index.environmentPolicy.variables).filter(path.isAbsolute)) await mkdir(directory, { recursive: true });
    const go = await executable("go", env.PATH);
    env.PATH = `${path.dirname(go.resolved)}${path.delimiter}${env.PATH}`;
    index.environmentPolicy.selectedGo = go;
    index.environmentPolicy.executionPathPrefix = path.dirname(go.resolved);
    index.tools.push({ name: "node", version: process.version, executable: await realpath(process.execPath) });
    const discovered = await capture("tool-discovery", root, "command -v go");
    assert.equal(discovered.record.exitCode, 0, "NATIVE_EXECUTABLE_DISCOVERY_COMMAND_FAILED");
    assert.equal(await realpath(discovered.output.trim()), go.resolved);
    const version = await capture("go-version", root, "go version");
    assert.equal(version.record.exitCode, 0, "NATIVE_VERSION_COMMAND_FAILED");
    assert.match(version.output, /^go version go1\.27\.1 [^\r\n]+\n$/, "NATIVE_GO_VERSION_MISMATCH");
    index.tools.push({ name: "go", version: version.output.trim(), executable: go.resolved, receipt: version.record.receipt });
    const configuration = await capture("go-environment", root,
      "go env -json GOVERSION GOROOT GOENV GOWORK GOTOOLCHAIN GOPROXY GOSUMDB GOCACHE GOMODCACHE GOFLAGS");
    assert.equal(configuration.record.exitCode, 0, "NATIVE_ENV_COMMAND_FAILED");
    index.goEnvironment = JSON.parse(configuration.output);
    // Go reports an empty configuration path for GOENV=off, rather than echoing "off".
    assert.equal(index.goEnvironment.GOENV, "");
    for (const key of ["GOWORK", "GOTOOLCHAIN", "GOPROXY", "GOSUMDB", "GOCACHE", "GOMODCACHE"]) assert.equal(index.goEnvironment[key], env[key]);
    assert.equal(index.goEnvironment.GOFLAGS, "");
    const inventories = {};
    for (const [project, sourceFiles] of Object.entries(projects)) {
      inventories[project] = [];
      for (const [name, content] of Object.entries(sourceFiles)) {
        const original = await artifact(`programs/${project}/${name}`, content);
        const file = `fixture-programs/${project}/${name}`;
        await mkdir(path.dirname(local(file)), { recursive: true });
        await copyFile(local(original.file), local(file), constants.COPYFILE_EXCL);
        const copy = await readFile(local(file));
        assert.equal(sha256(copy), original.sha256, "FIXTURE_SOURCE_COPY_CHANGED");
        const saved = { file, bytes: copy.length, sha256: sha256(copy), originalSource: original, license: "MIT", origin: "original; no donor" };
        inventories[project].push(saved);
        index.sources.push(saved);
      }
    }
    assert.ok(names.every((name) => name.length >= 90 && /^[A-Za-z0-9]+$/.test(name)));
    index.fixtureIntent = { module: moduleName, passingIdentifiers: names, passingInstances: 12,
      repeatedAcrossPackages: ["alpha", "beta"], skipInstances: 1, criticalLogInstances: 1, sequentialTests: true };
    for (const [id, project, role, exit] of [["cold", "noise", "noise", 0], ["cached", "noise", "noise", 0],
      ["failure", "failure", "exact", 1], ["diagnostic", "diagnostic", "exact", 0], ["opaque", "opaque", "exact", 0]]) {
      const result = await capture(id, local(`programs/${project}`), command, inventories[project]);
      index.cases.push({ ...result.record, role, profile: "go-test-verbose", inspectionPending: true });
      assert.equal(result.record.exitCode, exit, `NATIVE_CASE_EXIT_MISMATCH: ${id}`);
      if (project === "noise") {
        for (const name of names) assert.equal(result.output.split(`--- PASS: ${name} (0.00s)`).length - 1, 2);
        assert.ok(result.output.includes("HUGR_GO_CRITICAL_SENTINEL"));
        assert.ok(result.output.includes("HUGR_GO_SKIP_SENTINEL: indisponível café 🧭"));
        assert.ok(result.output.includes(`${moduleName}/empty`));
        if (id === "cached") assert.equal(result.output.split("(cached)").length - 1, 2);
        else assert.ok(!result.output.includes("(cached)"));
      } else assert.ok(result.output.includes(`HUGR_GO_${project === "failure" ? "FAILURE" : project === "diagnostic" ? "DIAGNOSTIC" : "OPAQUE"}_SENTINEL`));
    }
    for (const source of index.sources) {
      assert.equal(sha256(await readFile(local(source.originalSource.file))), source.sha256, "EXECUTED_SOURCE_CHANGED");
      assert.equal(sha256(await readFile(local(source.file))), source.sha256, "COPIED_SOURCE_CHANGED");
    }
    index.state = "captured-awaiting-lead-inspection";
  } catch (error) {
    blocker = error;
    index.state = "blocked";
    index.failedCaptures.push({ phase: "preparation-or-validation", active: active ?? null, error: error.stack });
  } finally {
    index.failedInventory = await json("failed-captures.json", index.failedCaptures);
    index.sourceInventory = await json("source-inventory.json", index.sources);
    index.provenance = await artifact("SOURCES.md", `# Go native evidence preparation\n\nOriginal MIT fixture programs; no donor repositories or dependencies.\nProducer: ${index.producer.script ?? script}\nProducer SHA-256: ${index.producer.sourceSHA256 ?? "unavailable"}\nBaseline: ${baseline}\nHead at capture: ${index.head ?? "unavailable"}\nCommand: \`${command}\`\nGo: ${index.tools.find((tool) => tool.name === "go")?.version ?? "unavailable"}\n\nExact executed sources and copies: source-inventory.json.\nExact commands, cwd, isolated settings, versions, launch/exit/timeout/encoding/cleanup facts: capture-index.json and capture receipts.\nFailed preparation/launch/capture/validation: failed-captures.json.\n\n${index.limits.map((limit) => `- ${limit}`).join("\n")}\n`);
    const frozen = await json("capture-index.json", index);
    await artifact("capture-index.sha256", `${frozen.sha256}\n`);
    await chmod(local("capture-index.json"), 0o400);
    console.log(JSON.stringify({ state: index.state, root, index: frozen, cases: index.cases.map(({ id, exitCode, complete, original }) => ({ id, exitCode, complete, original })), blocker: blocker?.message }, null, 2));
  }
  if (blocker) throw blocker;
}

collect().catch((error) => { console.error(error.stack); process.exitCode = 1; });
